''' naming of variables is a very important part of programming. It should be meaningful.
some rules for naming variables are:
1. variable name should start with a letter or underscore(_).ex = _car or car
2. variable name can only contain letters, numbers, and underscores.ex = car_1 or car1
3. variable name should not be a reserved keyword.ex = if, else, for , while, class etc.
here keywords are the words which are reserved by python for its own use. 
we can't use them as variable names. such as if, else, while, for, break, continue, def, class, etc.
'''

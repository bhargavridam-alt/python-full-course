#Operators are mathematical symbols that perform calculations on variables and values.
#for now we will discuss only +, -, *, /, %, **,and,or,not.
#these operators are used to perform arithmetic operations, logical operations, and more.
#by using these operators, we can perform calculations and make decisions in our code.
#ex..
x = 5
y = 2
#addition
print(x + y) #output: 7
#similarly, subtraction
print(x - y) #output: 3
#multiplication
print(x * y) #output: 10
#division
print(x / y) #output: 2.5
#modulus        
print(x % y) #output: 1
#exponentiation
print(x ** y) #output: 25   
#logical operators are used to combine conditional statements.
# let say we have two variables x and y, we can use logical operators to combine them and make decisions in our code.
#if x>0 and y>0, then we can say that both x and y are positive numbers.
#and operator
print(x > 0 and y > 0) #output: True
#or operator
print(x > 0 or y < 0) #output: True
#not operator
print(not(x > 0)) #output: False

#now we are gonna learn about typecasting and input in python and printing the output.
# print is a function that is used to display output to the console. It can take multiple arguments and print them in a single line or on separate lines.
# typecasting is the process of converting one data type to another.
# input is a function that is used to take input from the user.
#ex..
name = input("Enter your name: ") # this will take input from the user and store it as a string.
#here we have to take a input from the user.
#note: input() always take data as string.
#now the concept of typecasting comes into play when we want to convert the input data type to another data type.
#for example, if we want to take an integer input from the user, we can use
age = int(input("Enter your age: ")) # this will take input from the user and convert it to an integer using typecasting.
# similarly, we can take float input from the user
height = float(input("Enter your height in meters: ")) # this will take input from the user and convert it to a float using typecasting.
# we can also take boolean input from the user
is_student = bool(input("Are you a student? (True/False): ")) # this will take input from the user and convert it to a boolean using typecasting.
# now we can print the output using the print function.
print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Is Student:", is_student)
